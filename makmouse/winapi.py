"""Dostęp do Windows API (Win32) przez ctypes - fundament wszystkich modułów systemowych.

ZA CO ODPOWIADA
    * stałe Windows (komunikaty WM_*, flagi Raw Input, flagi SendInput, ...),
    * struktury C odwzorowane w Pythonie (RAWINPUT, INPUT, MSLLHOOKSTRUCT, ...),
    * deklaracje funkcji z user32.dll i kernel32.dll (typy argumentów i wyników),
    * dwie drobne pomocnicze: rozmiar wirtualnego pulpitu i pozycja kursora.

NAJWAŻNIEJSZE ELEMENTY
    user32, kernel32 ....... biblioteki systemowe gotowe do wołania
    RAWINPUT, RAWHID, ...... struktury raportów Raw Input
    INPUT, MOUSEINPUT, KEYBDINPUT  struktury dla SendInput (generowanie wejścia)
    MAKMOUSE_SIGNATURE ..... znacznik zdarzeń wygenerowanych przez MAKMOUSE
    virtual_screen_rect(), cursor_pos()

POWIĄZANIA
    Nie importuje nic z projektu. Używany przez engine.py, devices.py, output.py,
    navigator.py i appwatch.py.

SZCZEGÓŁY
Wszystko czego potrzebuje MAKMOUSE jest tutaj - dzięki temu aplikacja nie wymaga
pywin32 ani żadnych innych bibliotek natywnych.
"""
